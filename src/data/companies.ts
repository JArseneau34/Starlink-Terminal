export function getAllTickerCompanies(): Company[] {
  const seen = new Set<string>();
  const out: Company[] = [];
  for (const company of [...COMPANIES, ...COMMODITY_COMPANIES, ...AI_COMPANIES]) {
    if (company.type === 'public' && !seen.has(company.symbol)) {
      seen.add(company.symbol);
      out.push(company);
    }
  }
  return out;
}

export const PUBLIC_SYMBOLS = getAllTickerCompanies()
  .map((c) => c.symbol)
  .sort();

export const ALL_TRACKED_SYMBOLS = (() => {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const company of [...COMPANIES, ...COMMODITY_COMPANIES, ...AI_COMPANIES]) {
    const sym = company.symbol.toUpperCase();
    if (seen.has(sym)) continue;
    seen.add(sym);
    out.push(sym);
  }
  return out;
})();

export function getCompanyBySymbol(symbol: string): Company | undefined {
  return (
    COMPANIES.find((c) => c.symbol.toUpperCase() === symbol.toUpperCase()) ??
    getCommodityBySymbol(symbol) ??
    getAiBySymbol(symbol)
  );
}

export function filterCompaniesBySector(
  companies: Company[],
  sector: string,
  showPrivate = true
): Company[] {
  return companies.filter((c) => {
    if (!showPrivate && c.type === 'private') return false;
    if (sector === 'all') return true;
    return c.sectorTab === sector;
  });
}
