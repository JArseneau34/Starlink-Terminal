export function normalizePadName(raw: string): string {
  const s = raw.toLowerCase();
  if (s.includes('39a') || s.includes('lc-39a')) return 'LC-39A';
  if (s.includes('40') && (s.includes('slc') || s.includes('cape'))) return 'SLC-40';
  if (s.includes('4e') || s.includes('vandenberg')) return 'SLC-4E';
  if (s.includes('1a') && s.includes('mahia')) return 'LC-1A';
  if (s.includes('576')) return 'LC-576E';
  if (s.includes('41') && s.includes('cape')) return 'SLC-41';
  if (s.includes('37b')) return 'SLC-37B';
  if (s.includes('kourou') || s.includes('guiana') || s.includes('ela')) return 'Kourou ELA-4';
  if (s.includes('satish') || s.includes('sriharikota')) return 'Satish Dhawan';
  if (s.includes('wallops') || s.includes('mid-atlantic')) return 'LC-2';
  const short = raw.split(',')[0]?.trim() ?? raw;
  return short.length > 14 ? `${short.slice(0, 12)}…` : short;
}
